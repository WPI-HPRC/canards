#pragma once

// The flight attitude law: a gain-scheduled LQR
// (docs/HANDOFF-flight-skeleton-2026-11-20.md, section 8.1).
//
// Ported from Voyager-launch-controller controller.cpp (lqrController and
// lookupGains). The arithmetic is unchanged. Only the axis labels moved, from
// the old controller frame (x pitch, y yaw, z roll) to the team frame used
// everywhere in this repo (x roll/nose, y pitch, z yaw). The canard numbering,
// the mixing and the gain table are the same as before. A test feeds both the
// old code and this port the same situations and requires the same commands
// (test/test_attitude_control).
//
// DESIGN ASSUMPTIONS THE GAINS CARRY
//   - compute() is called once every 5 ms (200 Hz).
//   - Each servo follows its command as a first-order lag of 30 ms.
//   The law has no state and no dt, so neither number appears in this code:
//   both are baked into the gain table. NOTHING CHECKS THE CALL RATE. If the
//   control loop does not run at 200 Hz, or the servos are slower or are only
//   updated every 20 ms, the gains are for a different system and the table
//   must be regenerated by GNC.
//
// THE LAW
//   Three single-axis laws, v = -(k_angle * error + k_rate * rate + k_servo * s),
//   where s is the canard deflection that drives that axis:
//       roll   s = mean of the four canards
//       pitch  s = (canard 2 - canard 0) / 2
//       yaw    s = (canard 3 - canard 1) / 2
//   The gains come from the table by speed, interpolated linearly between
//   rows. Below the first row and above the last, the end row is held.
//   Pitch and yaw share one set of gains. The roll error is limited to
//   kRollErrorLimitRad before its gain is applied.
//
//   ROLL PRIORITY. No canard is ever commanded past the limit. Roll takes what
//   it asks for, up to the whole limit. Pitch and yaw are then scaled down
//   together, by one factor, into whatever roll left over. So a roll demand at
//   the limit leaves pitch and yaw nothing. This is the normal operating
//   state, not a corner case: with a 4 deg limit, about 0.4 deg of tilt
//   already asks for all of it.
//
//   Mixing back to the canards:
//       canard 0 = roll - pitch      canard 2 = roll + pitch
//       canard 1 = roll - yaw        canard 3 = roll + yaw
//
// The servo model and the linkage maths of the old file are NOT here. The
// servo model lives in ServoControl. The linkage is unused, because the
// encoder sits on the canard shaft.
//
// No Arduino, no heap, no clock, no state between calls.

#include "AttitudeControl/AttitudeController.h"

class LqrAttitudeController final : public AttitudeController {
 public:
  // A roll error larger than this is treated as this much. The old code calls
  // it anti-windup: while the error is beyond it, the roll rate the law
  // settles at stops growing with the error. 10 deg comes with the gain
  // design, from the old controller.h (kRollErrorLimit).
  static constexpr float kRollErrorLimitRad = 10.0f * 0.017453292519943295f;

  // `table` has `rows` rows of 7 numbers: speed [m/s], then roll angle / rate
  // / servo gains, then pitch-and-yaw angle / rate / servo gains (the format
  // of lqr_gain_table.h). It is not copied and must outlive this object.
  //
  // `canardLimitRad` is the largest canard command, and also what the
  // roll-priority split divides up. Pass FlightConfig::kCanardLimitRad, so
  // that there is one limit in the program. A smaller clamp applied
  // afterwards would cut roll's share and defeat roll priority.
  //
  // The table is passed in, not picked by a macro, so tests can pin a fixed
  // table while flight uses the flight table.
  //
  // Both are checked once, here. See valid().
  LqrAttitudeController(const float (*table)[7], int rows, float canardLimitRad);

  // Uses the flight table (AttitudeControl/lqr_gain_table.h).
  explicit LqrAttitudeController(float canardLimitRad);

  // False if the table or the limit given at construction cannot be used:
  //   - fewer than 2 rows, or no table;
  //   - a speed that is not finite, or not larger than the row before it;
  //   - a gain that is not finite;
  //   - a limit that is not finite or not above zero.
  // compute() then always returns false with zero commands.
  bool valid() const { return valid_; }

  float canardLimitRad() const { return canardLimitRad_; }

  // See AttitudeController. Returns false, with all four commands zero, if:
  //   - valid() is false;
  //   - ANY input is not finite: attitude error, body rate, canard angles or
  //     speed;
  //   - the arithmetic overflows (finite but absurdly large inputs).
  // Otherwise returns true and every command is within +/- the limit.
  //
  // `canardCommand` may be the same array as `in.canardAngle`.
  bool compute(const AttitudeControlInput& in, float canardCommand[4]) override;

 private:
  // The six gains at `speed`: [0] roll angle, [1] roll rate, [2] roll servo,
  // [3] pitch/yaw angle, [4] pitch/yaw rate, [5] pitch/yaw servo.
  void lookupGains(float speed, float k[6]) const;

  // The law itself. `command` is only meaningful if this returns true.
  bool law(const AttitudeControlInput& in, float command[4]) const;

  const float (*table_)[7];
  int rows_;
  float canardLimitRad_;
  bool valid_;
};
